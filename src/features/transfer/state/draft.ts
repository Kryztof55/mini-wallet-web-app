import { identifierKey, type Identifier } from '@/core/identifier';
import type { Money } from '@/core/money';

/** TS-03 §4: a saved favorite or a one-off contact (not saved, or saving failed). */
export type Recipient =
  | {
      readonly kind: 'contact';
      readonly contactId: string;
      readonly name: string;
      readonly maskedIdentifier: string;
    }
  | {
      readonly kind: 'oneOff';
      readonly name: string;
      readonly identifier: Identifier;
      readonly maskedIdentifier: string;
    };

/** Shown once on the next step after choosing a new contact (UIR-TX-06…08). */
export type ContactNotice =
  | { readonly kind: 'saved'; readonly name: string }
  | { readonly kind: 'duplicate'; readonly name: string }
  | { readonly kind: 'save_failed' };

export type TransferDraft = {
  readonly recipient: Recipient | null;
  readonly amount: Money | null;
  readonly concept: string;
  /** Idempotency key of the attempt (BR-07); set when the summary is reached. */
  readonly attempt: { readonly key: string; readonly fingerprint: string } | null;
  readonly notice: ContactNotice | null;
  /** Set when the transfer succeeded; the guard then sends the user Home (TS-04). */
  readonly completed: boolean;
};

export const emptyDraft: TransferDraft = {
  recipient: null,
  amount: null,
  concept: '',
  attempt: null,
  notice: null,
  completed: false,
};

export type DraftAction =
  | {
      readonly type: 'recipientSelected';
      readonly recipient: Recipient;
      readonly notice?: ContactNotice;
    }
  | { readonly type: 'amountConfirmed'; readonly amount: Money; readonly concept: string }
  | { readonly type: 'conceptChanged'; readonly concept: string }
  /** `newKey` is generated by the caller so the reducer stays pure. */
  | { readonly type: 'summaryReached'; readonly newKey: string }
  | { readonly type: 'noticeShown' }
  | { readonly type: 'completed' }
  | { readonly type: 'reset' }
  /** "Enviar otra vez" (FS-04): start a new draft with this recipient. */
  | { readonly type: 'seedRecipient'; readonly recipient: Recipient };

function recipientKey(recipient: Recipient): string {
  return recipient.kind === 'contact'
    ? `contact:${recipient.contactId}`
    : `oneOff:${identifierKey(recipient.identifier)}`;
}

/** Same recipient, amount and concept → same fingerprint → same attempt key (BR-07). */
export function draftFingerprint(
  draft: Pick<TransferDraft, 'recipient' | 'amount' | 'concept'>,
): string {
  return JSON.stringify([
    draft.recipient ? recipientKey(draft.recipient) : null,
    draft.amount ? draft.amount.amountMinor : null,
    draft.concept.trim(),
  ]);
}

export function draftReducer(draft: TransferDraft, action: DraftAction): TransferDraft {
  switch (action.type) {
    case 'recipientSelected':
      return {
        ...draft,
        recipient: action.recipient,
        notice: action.notice ?? null,
        completed: false,
      };
    case 'amountConfirmed':
      return { ...draft, amount: action.amount, concept: action.concept };
    case 'conceptChanged':
      return { ...draft, concept: action.concept };
    case 'summaryReached': {
      const fingerprint = draftFingerprint(draft);
      if (draft.attempt && draft.attempt.fingerprint === fingerprint) return draft;
      return { ...draft, attempt: { key: action.newKey, fingerprint } };
    }
    case 'noticeShown':
      return draft.notice ? { ...draft, notice: null } : draft;
    case 'completed':
      return { ...draft, completed: true };
    case 'reset':
      return emptyDraft;
    case 'seedRecipient':
      return { ...emptyDraft, recipient: action.recipient };
    default: {
      const exhaustive: never = action;
      return exhaustive;
    }
  }
}

/** True when the user has entered anything worth confirming before cancel (UIR-TX-20). */
export function hasDraftData(draft: TransferDraft): boolean {
  return draft.recipient !== null || draft.amount !== null || draft.concept.trim() !== '';
}

export type TransferStep = 'recipient' | 'amount' | 'summary';

/** UIR-TX-14: the first step whose prerequisites are missing, or null if `step` may render. */
export function requiredStep(draft: TransferDraft, step: TransferStep): TransferStep | null {
  if (step === 'recipient') return null;
  if (!draft.recipient) return 'recipient';
  if (step === 'summary' && !draft.amount) return 'amount';
  return null;
}
